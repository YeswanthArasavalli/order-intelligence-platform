"""
Order Intelligence Platform — Centralised Configuration
=======================================================
Loads all environment variables using Pydantic Settings.
Fails fast with a clear error message if any required variable is missing.

Usage:
    from utils.config import settings

    print(settings.kafka_bootstrap_servers)
    print(settings.postgres_host)
"""

from pydantic import Field, field_validator
from pydantic_settings import BaseSettings, SettingsConfigDict


class Settings(BaseSettings):
    """
    Platform-wide configuration.
    All values loaded from environment variables / .env file.
    """

    model_config = SettingsConfigDict(
        env_file=".env",
        env_file_encoding="utf-8",
        case_sensitive=False,
        extra="ignore",
    )

    # -------------------------------------------------------------------------
    # KAFKA
    # -------------------------------------------------------------------------
    kafka_bootstrap_servers: str = Field(
        default="kafka:9092",
        description="Kafka bootstrap server(s), comma-separated",
    )
    kafka_cluster_id: str = Field(
        description="KRaft cluster ID — generated by make generate-cluster-id",
    )
    schema_registry_url: str = Field(
        default="http://schema-registry:8081",
        description="Confluent Schema Registry base URL",
    )
    schema_compatibility_level: str = Field(
        default="BACKWARD",
        description="Schema compatibility mode for all topics",
    )

    # -------------------------------------------------------------------------
    # MINIO / DATA LAKE
    # -------------------------------------------------------------------------
    minio_endpoint: str = Field(
        default="http://minio:9000",
        description="MinIO S3-compatible API endpoint",
    )
    minio_root_user: str = Field(
        default="minioadmin",
        description="MinIO access key",
    )
    minio_root_password: str = Field(
        description="MinIO secret key",
    )
    minio_bronze_bucket: str = Field(default="bronze")
    minio_silver_bucket: str = Field(default="silver")
    minio_gold_bucket: str = Field(default="gold")
    minio_checkpoint_bucket: str = Field(default="checkpoints")

    # -------------------------------------------------------------------------
    # POSTGRESQL
    # -------------------------------------------------------------------------
    postgres_host: str = Field(default="postgres")
    postgres_port: int = Field(default=5432)
    postgres_db: str = Field(default="order_intelligence")
    postgres_user: str = Field(default="oip_user")
    postgres_password: str = Field(description="PostgreSQL password")
    postgres_jdbc_url: str = Field(
        default="jdbc:postgresql://postgres:5432/order_intelligence"
    )

    @property
    def postgres_dsn(self) -> str:
        """SQLAlchemy-compatible connection string."""
        return (
            f"postgresql+psycopg2://{self.postgres_user}:{self.postgres_password}"
            f"@{self.postgres_host}:{self.postgres_port}/{self.postgres_db}"
        )

    # -------------------------------------------------------------------------
    # REDIS
    # -------------------------------------------------------------------------
    redis_host: str = Field(default="redis")
    redis_port: int = Field(default=6379)
    redis_max_memory: str = Field(default="256mb")
    redis_ttl_kpi: int = Field(default=600)
    redis_ttl_leaderboard: int = Field(default=300)
    redis_ttl_alert: int = Field(default=900)
    redis_ttl_dashboard: int = Field(default=60)

    # -------------------------------------------------------------------------
    # SPARK
    # -------------------------------------------------------------------------
    spark_master: str = Field(default="local[*]")
    spark_trigger_interval_seconds: int = Field(default=30)
    spark_checkpoint_dir: str = Field(
        default="s3a://checkpoints/streaming/"
    )
    spark_watermark_minutes: int = Field(default=2)

    # -------------------------------------------------------------------------
    # ALERTING
    # -------------------------------------------------------------------------
    alert_cooldown_minutes: int = Field(default=15)
    slack_webhook_url: str = Field(default="")
    pagerduty_integration_key: str = Field(default="")
    alert_revenue_drop_threshold: float = Field(default=0.70)
    alert_zscore_threshold: float = Field(default=3.0)

    # -------------------------------------------------------------------------
    # OBSERVABILITY
    # -------------------------------------------------------------------------
    prometheus_scrape_interval: str = Field(default="15s")

    # -------------------------------------------------------------------------
    # VALIDATORS
    # -------------------------------------------------------------------------
    @field_validator("kafka_cluster_id")
    @classmethod
    def kafka_cluster_id_must_be_set(cls, v: str) -> str:
        if not v or v.strip() == "":
            raise ValueError(
                "KAFKA_CLUSTER_ID is not set. "
                "Run: make generate-cluster-id"
            )
        return v

    @field_validator("minio_root_password")
    @classmethod
    def minio_password_min_length(cls, v: str) -> str:
        if len(v) < 8:
            raise ValueError("MINIO_ROOT_PASSWORD must be at least 8 characters")
        return v

    @field_validator("alert_revenue_drop_threshold")
    @classmethod
    def threshold_between_zero_and_one(cls, v: float) -> float:
        if not 0.0 < v < 1.0:
            raise ValueError(
                "ALERT_REVENUE_DROP_THRESHOLD must be between 0.0 and 1.0 "
                f"(got {v})"
            )
        return v


# ---------------------------------------------------------------------------
# Singleton — import this everywhere
# ---------------------------------------------------------------------------
settings = Settings()
